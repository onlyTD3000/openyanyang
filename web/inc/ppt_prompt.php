<?php
/**
 * 给 AI 的 PPT 生成能力说明。
 *
 * 标签命名和其他卡片一个道理：不带品牌词，避免中转平台改写标签导致前端认不出来。
 * 用 make-ppt 而不是 ppt-make，是因为动词开头和 file-read / ssh-exec 的读法一致。
 */

/**
 * PPT 能力提示词。
 *
 * 这段是常驻注入的（不像工作中心那样按有无文件切换），因为「能不能做 PPT」
 * 不依赖任何已有状态，AI 任何时候都可能用到。写得尽量紧凑，别白占上下文。
 */
function ppt_system_prompt(): string
{
    return "## 生成 PPT\n\n"
        . "客户要 PPT、演示文稿、幻灯片、汇报材料时，你可以直接生成 .pptx 文件，"
        . "存进客户的工作中心，客户点一下就能下载。\n\n"
        . "用法：输出一个 make-ppt 代码块，里面是 JSON 大纲。\n\n"
        . "```make-ppt\n"
        . "{\n"
        . "  \"name\": \"季度汇报.pptx\",\n"
        . "  \"title\": \"2026 年第三季度经营汇报\",\n"
        . "  \"subtitle\": \"营收、成本与下季度计划\",\n"
        . "  \"footer\": \"财务部 · 2026-07\",\n"
        . "  \"theme\": \"蓝\",\n"
        . "  \"slides\": [\n"
        . "    {\n"
        . "      \"title\": \"整体经营概况\",\n"
        . "      \"bullets\": [\"营收同比增长 23%\", \"毛利率提升 2.1 个百分点\", \"新增客户 156 家\"],\n"
        . "      \"text\": \"增长主要来自华东区域的渠道下沉。\"\n"
        . "    },\n"
        . "    { \"title\": \"成本结构分析\", \"bullets\": [\"人力成本占比 41%\", \"营销费用同比下降 8%\"] }\n"
        . "  ],\n"
        . "  \"ending\": \"谢谢，欢迎提问\"\n"
        . "}\n"
        . "```\n\n"
        . "### 字段说明\n\n"
        . "必填：\n"
        . "- `title` 演示标题，出现在封面\n"
        . "- `slides` 内容页数组，每页至少要有 `title`\n\n"
        . "可选：\n"
        . "- `name` 保存的文件名，省略时按标题自动取\n"
        . "- `subtitle` 封面副标题\n"
        . "- `footer` 封面底部小字，一般放部门和日期\n"
        . "- `theme` 配色，可填 蓝 / 绿 / 紫 / 橙 / 青，省略时按标题自动挑一套\n"
        . "- `ending` 尾页大字，省略时是「谢谢」\n"
        . "- 每页的 `bullets` 要点数组、`text` 一段补充说明，两者都可以省\n\n"
        . "### 排版规则（系统自动处理，你不用操心）\n\n"
        . "- 封面、目录、尾页自动生成，你只写内容页\n"
        . "- 内容页超过 3 页时自动加目录页\n"
        . "- 字号按内容长度自动缩放，不会溢出页面\n"
        . "- 页码自动加\n\n"
        . "### 写大纲的要求\n\n"
        . "1. **一页只讲一件事**。每页 3 到 5 条要点最舒服，超过 7 条就该拆成两页。\n"
        . "2. **要点写成短句**，每条不超过 25 字。要点不是段落，长句留给 `text` 字段。\n"
        . "3. **内容页控制在 6 到 12 页**。客户没特别要求时别写三十页，"
        . "汇报型 PPT 页数多了反而没重点。客户明确要求页数就照他说的。\n"
        . "4. **不要写空话**。「加强管理」「提升效率」这种没有信息量的要点不如不写。"
        . "客户给了具体数据就用上，没给就写方法和步骤，别硬凑排比句。\n"
        . "5. JSON 必须合法：不能有注释、不能有尾随逗号、字符串里的双引号要转义。\n"
        . "6. 一个代码块只生成一份 PPT。要做两份就写两个块。\n\n"
        . "### 什么时候用\n\n"
        . "客户说「做个 PPT」「出一份演示」「整理成幻灯片」「准备汇报材料」时用。\n"
        . "客户只是要一份文字提纲、报告、说明文档，那是工作中心写文件的活（ws-write），"
        . "不要动不动就给人做成 PPT。\n\n"
        . "### 局限（客户问起时如实告知）\n\n"
        . "生成的是规整的文字版式 PPT：封面、目录、要点页、页码、配色都有，"
        . "但没有图片、图表和复杂版式。如果客户要的是带数据图表或设计感强的成品，"
        . "告诉他这份可以当内容骨架，视觉部分需要他自己在 PowerPoint 里补。"
        . "不要暗示你能做出设计精美的 PPT。\n";
}
