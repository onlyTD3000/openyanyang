/**
 * 给 AI 的工作中心文件库能力说明。
 *
 * 当账号工作中心里有文件时注入，让 AI 知道：
 *  1. 它有一个持久化的文件库，可以存放产出的代码、文档、配置等
 *  2. 用 ws-read / ws-write / ws-patch 代码块读写文件
 *  3. 文件按名字引用（账号内虚拟相对路径），改写时自动留旧版本
 *
 * 标签命名注意：和 ssh-exec / file-read 同理，不带品牌词，避免中转平台改写。
 */

// 提示词里要报出体积与文件数上限的实际数值，这两个常量定义在 ws_files.php。
// 不引入的话直接引用常量会致命错误。
require_once __DIR__ . '/ws_files.php';
// 打包章节要引用 ws_zip.php 里的两个上限常量，不加载会致命错误（整个对话页白屏）
require_once __DIR__ . '/ws_zip.php';

/**
 * 生成工作中心相关的系统提示词。
 *
 * @param array $文件表 工作中心文件清单（name/kind/size/note），用于概览
 * @param bool  $展开   是否完整列出所有文件，false 时只列前 50 个
 */
function ws_system_prompt(array $文件表 = [], bool $展开 = false, bool $要打包 = true): string
{
    // $文件表 已不再使用（保留参数是为了不破坏既有调用方）：
    // 清单不进系统提示词了，改由 AI 用 ws-list 按需查。
    // 也因此空库不再提前 return——工具说明跟库里有没有文件无关，一律要说。
    unset($文件表, $展开);

    /* $要打包 决定是否带上「打包下载」那一节（约 700 字节）。
       打包是低频操作，绝大多数会话用不到，却每轮都在占前缀。
       默认 true 是为了不改变既有调用方的行为，由 api/chat.php 按需传 false。 */

    // 这段刻意做成「完全静态」：不含文件数、不含文件清单、不含任何随账号状态
    // 变化的内容。原因是它被注入系统提示词，而系统提示词是上游缓存的前缀
    // （见 inc/upstream_claude.php 的 cache_control）。一旦掺进易变内容，
    // 客户每写一个文件前缀就变一次，整段系统缓存失效、重新计一次写入费。
    // 打包场景恰好要连写多个文件，那样会连续失效多次。
    // 代价是 AI 手上没有现成清单，需要时得用 ws-list 查一次，多一轮往返。
    $概 = "## 工作中心文件库\n\n"
        . "你有一个专属的持久化文件库（客户看不到别人的，账号之间严格隔离），"
        . "用来存放你产出的代码、文档、配置、脚本、报表等。"
        . "写进去的东西会一直保留，下次对话仍然在，客户可以在工作中心页查看和下载。\n\n"
        . "### 查看有哪些文件\n\n"
        . "你的上下文里**没有**文件清单，需要知道库里有什么就查一次：\n\n"
        . "```ws-list\n"
        . "```\n\n"
        . "块内留空即可。要按名字筛选就写 `q: 关键词`。\n"
        . "改已有文件、或客户提到「刚才那个文件」而你不确定叫什么时，先 ws-list 查清楚，"
        . "别凭猜测写文件名——名字猜错会新建一个多余文件，而不是改到原来那个。\n\n"
        . "### 读文件\n\n"
        . "```ws-read\n"
        . "name: 文件名（账号内相对路径）\n"
        . "```\n\n"
        . "例如 `name: 报价单.md` 或 `name: scripts/deploy.sh`。\n"
        . "文件名就是上面列表里的那些名字，照抄即可。\n\n"
        . "### 写文件\n\n"
        . "```ws-write\n"
        . "name: 文件名\n"
        . "note: 一句话说明这个文件是干什么的\n"
        . "---\n"
        . "（这里放文件的完整内容）\n"
        . "```\n\n"
        . "name 下面的三个减号是分隔符，必须有；分隔符之后的所有内容都算文件正文。\n\n"
        . "**文件名规则**：\n"
        . "- 可以带目录，如 `docs/api.md`、`src/utils.py`，会按目录归类\n"
        . "- 不能以 / 开头，不能包含 ..，不能超过 8 层目录\n"
        . "- 同名文件会被覆盖（覆盖前自动留旧版本快照，改坏了能恢复）\n\n"
        . "**什么时候用工作中心写文件**：\n"
        . "- 你给客户产出的代码、配置、文档、脚本、数据表等，需要持久保存供客户取用的\n"
        . "- 客户要求「写个文件」「生成一份报告」「输出配置」这类明确的产出物\n"
        . "- 多轮对话里要持续维护的文件（比如客户让你「再改改刚才那个脚本」，"
        . "你就先 ws-read 读出来，改完再 ws-write 写回去）\n\n"
        . "**不要用工作中心干什么**：\n"
        . "- 不要把它当临时草稿本，只是演示一段代码、解释一个概念时直接写在消息里就行\n"
        . "- 不要把客户服务器上的代码拉到这里改——那是「项目代码仓」的活（file-read / file-write）\n"
        . "- 不要把对话记录、日志这类客户没要求的东西往里塞\n\n"
        . "### 局部补丁\n\n"
        . "文件很大、只改几行时，不用把整个文件重写一遍：\n\n"
        . "```ws-patch\n"
        . "name: 文件名\n"
        . "note: 改了什么\n"
        . "<<<<<<< 原文\n"
        . "（要被替换掉的原片段，照抄原文）\n"
        . "=======\n"
        . "（替换后的新片段）\n"
        . ">>>>>>>\n"
        . "```\n\n"
        . "补丁按内容定位，原片段必须在文件里唯一。不唯一会报错，补上下文即可。\n\n"
        . "### 删除文件\n\n"
        . "不再需要的文件可以删除：\n\n"
        . "```ws-delete\n"
        . "name: 文件名\n"
        . "```\n\n"
        . "删除后文件会进入回收站，30天内可恢复。\n"
        . "批量删除可以一次列多个：\n\n"
        . "```ws-delete\n"
        . "name: 文件1.txt\n"
        . "name: 文件2.md\n"
        . "name: scripts/old.sh\n"
        . "```\n\n"
        . ($要打包 ? (
          "### 打包下载\n\n"
        . "客户要「打包」「压缩包」「zip」「一起发我」「打包发我」时，"
        . "先用 ws-write 把文件逐个写进工作中心，再输出一个 ws-zip 块把它们打成一个包：\n\n"
        . "```ws-zip\n"
        . "name: 项目源码.zip\n"
        . "note: 一句话说明包里是什么\n"
        . "---\n"
        . "src/app.py\n"
        . "src/utils.py\n"
        . "requirements.txt\n"
        . "README.md\n"
        . "```\n\n"
        . "分隔符后面一行一个文件名，照抄工作中心里的名字。\n"
        . "包里会保留目录结构，客户解压出来就是原来的层次。\n\n"
        . "**打包的正确顺序**（做错了包里会是空的）：\n"
        . "1. 先把每个文件用 ws-write 写好，等系统回执确认写入成功\n"
        . "2. 确认无误后再输出 ws-zip，列出刚写的那些文件名\n"
        . "3. 不能在同一轮里边写边打包——文件还没落盘，打包会说文件不存在\n\n"
        . "**限制**：一个包最多 " . 工作区打包数上限 . " 个文件，"
        . "打包前总体积不超过 " . size_text(工作区打包体积上限) . "。\n"
        . "只能打包工作中心里已有的文件，打不了客户服务器上的文件、"
        . "也打不了别人账号的文件。包名重复时系统自动加序号，不会覆盖旧包。\n\n"
          ) : "")
        . "### 必须遵守\n\n"
        . "1. 写文件前先想清楚：这个东西客户需要持久保存吗？不需要就别写。\n"
        . "2. 一个代码块只写一个文件，且一条回复只放一个卡片。"
        . "要写多个文件就分多轮回复，每轮一个卡片——"
        . "一条回复放多张卡片会导致卡片之间的正文在渲染时丢失。\n"
        . "3. ws-write 的正文必须是**完整**文件内容，不能写「其余部分不变」"
        . "或省略号，写了就真的会把文件截断。\n"
        . "4. 改已有文件前先 ws-read 读出来看清原内容，别凭记忆瞎改。\n"
        . "5. 文本文件才能用这套读写，图片、压缩包之类二进制文件读不出来。\n"
        // 限额从常量读，别写死。不写清楚 AI 会自己编一套数字出来。
        . "6. 限额：单个文件最大 " . size_text(工作区文本上限) . "，"
        . "一个账号最多 " . 工作区文件数上限 . " 个文件。空间上限按账号配额算，"
        . "写入失败时系统会提示已满，那就提醒客户去工作中心删掉一些旧文件。\n"
        . "7. ws-write 和 ws-patch 的正文长度没有行数或字符数限制，"
        . "只要文件不超过体积上限就行。不要自己假设「一次只能写 150 行」"
        . "这类限制而把一个文件拆成几次写，那样只会多耗轮次，还容易写残。\n";

    return $概;
}

/**
 * 取当前账号工作中心的文件清单，用于注入提示词。
 *
 * @param int  $用户id
 * @param bool $只文本  true 时只列可编辑的文本文件，跳过图片和二进制
 * @return array 文件清单，每项包含 name / kind / size / note
 */
function ws_file_list_for_prompt(int $用户id, bool $只文本 = false): array
{
    $条件 = 'user_id=?';
    $参   = [$用户id];
    if ($只文本) {
        $条件 .= ' AND kind=\'text\'';
    }
    try {
        $行 = db_all('SELECT name, kind, size, note FROM uploads
                      WHERE ' . $条件 . ' ORDER BY updated_at DESC, id DESC LIMIT 150', $参);
    } catch (Throwable $e) {
        return [];          // 表还没建或字段还没加，返回空即可
    }
    return $行 ?: [];
}

/**
 * 文件库为空时的简短说明。
 *
 * 库是空的也得告诉 AI 有这个能力，否则它不会主动往里写东西，
 * 客户让它「写个脚本」时它就只把代码贴在聊天里，关掉对话就没了。
 * 这段刻意写短，避免空库时白占上下文。
 */
function ws_empty_prompt(): string
{
    return "## 工作中心文件库\n\n"
        . "你有一个专属的持久化文件库（账号之间严格隔离，客户只看得到自己的），"
        . "现在还是空的。产出需要客户长期取用的东西时写到这里，"
        . "客户可以在「工作中心」页面查看、编辑、下载。\n\n"
        . "写文件：\n\n"
        . "```ws-write\n"
        . "name: 文件名（可带目录，如 scripts/deploy.sh）\n"
        . "note: 一句话说明用途\n"
        . "---\n"
        . "（完整文件内容）\n"
        . "```\n\n"
        . "读文件：\n\n"
        . "```ws-read\n"
        . "name: 文件名\n"
        . "```\n\n"
        . "删除文件：\n\n"
        . "```ws-delete\n"
        . "name: 文件名\n"
        . "```\n\n"
        . "打包下载（客户要压缩包时用，先写文件、等回执，再打包）：\n\n"
        . "```ws-zip\n"
        . "name: 打包名.zip\n"
        . "---\n"
        . "文件1\n"
        . "文件2\n"
        . "```\n\n"
        . "规则：正文必须完整，不能写「其余不变」之类的省略；一个块只写一个文件；"
        . "同名会覆盖（自动留旧版快照）。只是举例说明、演示片段就别往里写，"
        . "直接贴在消息里即可。\n"
        . "打包必须分两步：先 ws-write 写完并等系统回执，再输出 ws-zip。"
        . "同一轮里边写边打包会失败，因为文件还没落盘。\n";
}
