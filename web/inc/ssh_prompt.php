<?php
/**
 * 给 AI 的远程执行能力说明。
 * 仅当用户已登记至少一台服务器时才注入，避免无谓占用上下文。
 */

// 提示词里要报出超时与输出上限的实际数值，这两个常量定义在 ssh_run.php。
// 不引入就取不到，提示词只能走兜底值，改了配置这里会对不上。
require_once __DIR__ . '/ssh_run.php';

/**
 * 生成远程执行相关的系统提示词。
 *
 * 安全策略已按客户要求取消：命令行不再有任何拦截，改文件也可以用命令行。
 * 但改文件仍建议优先走 SFTP（sftp-* 代码块，见 sftp_prompt.php），
 * 因为那条通道每次写入前会留备份、有还原记录，命令行没有这层保护。
 * 这里的措辞是「建议」而非「禁止」，不要写成会被拒绝，否则与实际行为不符。
 *
 * 注意：代码块标签用 ssh-exec，不要带任何品牌词。
 * 实测部分中转平台会改写提示词里的品牌名（kiro 会被替换成 claude），
 * 标签一旦被改写，前端就认不出这个块，卡片渲染不出来。
 *
 * @param array $hosts    当前用户已登记的主机（只取 id 与 name/host）
 * @param int   $默认主机 当前项目绑定的主机 id，会在列表里标注为默认，0 表示无
 * @param bool  $有SFTP   当前项目是否已具备 SFTP 直连条件（绑了主机且填了部署目录）
 * @param bool  $启用工具 是否启用了 Function Calling（默认 true）
 */
function ssh_system_prompt(array $hosts, int $默认主机 = 0, bool $有SFTP = false, bool $启用工具 = true): string
{
    if (!$hosts) {
        return '';
    }
    $lines = [];
    foreach ($hosts as $h) {
        $标 = ((int) $h['id'] === $默认主机) ? '（本项目默认）' : '';
        $lines[] = '  - 编号 ' . (int) $h['id'] . '：' . $h['name']
            . '（' . $h['host'] . '，登录用户 ' . $h['username'] . '）' . $标;
    }

    // 改文件的建议去向：具备 SFTP 条件时优先用 sftp-* 块（有备份和还原记录），
    // 不具备时直接用命令行改也行，不再拦。
    $改文件去向 = $有SFTP
        ? "改文件优先用 sftp-write / sftp-patch / sftp-delete 代码块（见上一节），"
          . "那条通道每次写入前会自动留备份，改错了能还原。"
        : "本项目没绑定服务器或没填部署目录，没有 SFTP 直连通道，"
          . "改文件就用命令行处理。";

    // 当启用了 Function Calling 时，明确禁止代码块格式，强制使用工具调用
    $格式说明 = $启用工具 
        ? "### 执行命令的格式\n\n"
          . "**必须使用工具调用（Function Calling）**：你已经被赋予了 ssh_exec 工具，"
          . "需要执行命令时直接调用该工具，传入 host（服务器编号）和 cmd（命令）参数。\n\n"
          . "**禁止使用代码块格式**：不要生成 ```ssh-exec 代码块，那是旧版本的格式，"
          . "现在必须用工具调用。如果你生成代码块，命令不会被执行。\n\n"
        : "### 执行命令的格式\n\n"
          . "需要执行命令时，用下面这种代码块包住，一次只写一条：\n\n"
          . "```ssh-exec\n"
          . "host: 服务器编号\n"
          . "cmd: 要执行的命令\n"
          . "```\n\n"
          . "代码块的标签必须原样写成 ssh-exec，写成别的词系统识别不了。\n\n";

    return "## 远程服务器操作能力\n\n"
        . "用户已登记以下服务器，你可以在上面执行命令：\n"
        . implode("\n", $lines) . "\n\n"
        . "### 命令行没有任何限制\n\n"
        . "命令行可以执行任何命令，没有黑名单、没有风险分级、不需要用户确认。"
        . "诊断排查、安装配置、起停服务、改文件、装环境，都可以直接做。\n\n"
        . "改文件的建议：" . $改文件去向 . "\n"
        . "sed -i、tee、heredoc（<<EOF）、> 重定向、vi 之类的写法现在都能正常执行，"
        . "SFTP 通道报错时可以直接改用命令行，不必卡在那里。\n\n"
        . $格式说明
        . "### 执行方式\n\n"
        . "用户已开启自动执行：命令会在你输出后**立即执行**，不需要用户点确认，"
        . "执行结果会自动作为下一轮的用户消息发给你。所以：\n\n"
        . "1. 不要问「要我执行吗」「是否需要我查看」这类征询，直接调用工具执行命令。\n"
        . "2. 也不要说「请确认」「等你确认后我再」，说了也没人点，纯属浪费一轮对话。\n"
        . "3. **直接调用工具，不要用文字描述**：看到需要执行命令时，**立即调用 ssh_exec 工具**，"
        . "不要说「我来执行」「第一次执行」等描述性文字，直接调用工具即可。\n"
        . "4. **一次可以调用多个工具**：如果用户要求执行多个命令（如「date、whoami、pwd」），"
        . "可以在同一个回复中多次调用 ssh_exec 工具，系统会按顺序执行。\n"
        . "5. **不要用 && 或 ; 连接多个命令**：每个命令都要单独调用一次工具，不要合并成一条命令。\n\n"
        . "### 必须遵守\n\n"
        . "1. 命令会真的改动服务器，立即执行且没有人工复核，"
        . "危险命令也不会被系统拦下来。动手前先想清楚影响。\n"
        . "2. 排查问题时先用只读命令看清现状，再动手改，不要凭猜测直接改。\n"
        . "3. 每条会改动系统的命令，在执行前用一句话说明它会做什么。\n"
        . "4. 删除、重启、覆写配置这类不可逆操作，先确认路径和目标对不对，"
        . "必要时先备份再动手。没有安全策略兜底，写错了就是真的丢数据。\n"
        . "5. 用户没让你操作服务器时，不要主动执行命令。\n"
        /* 命令现在一律在远端后台跑，前端轮询进度，没有秒数上限了。
           这里必须说清楚「别自己套 nohup」：平台已经套了一层，
           AI 再套一层的话，内层进程脱离了平台的 PID 记录，
           「停止」按钮杀不掉它，日志也收不全。
           输出上限这个数从常量读，别写死，改了 ssh_run.php 这里才不会对不上。 */
        . "6. 命令跑多久都行，没有超时限制：平台会把它放到服务器后台执行并实时回传进度，"
        . "编译、下载、装依赖这类长任务直接写普通命令就行。\n"
        . "   正因为平台已经做了后台化，你不要自己再套 nohup、setsid、& 或 screen —— "
        . "套了平台就跟踪不到真正在干活的那个进程，用户点停止停不下来，输出也收不全。\n"
        . "   单次回传的输出超过 " . (defined('SSH_OUT_LIMIT') ? SSH_OUT_LIMIT : 40000)
        . " 字符会被截断，输出特别多的命令自己加 tail、grep 收一收。\n"
        . "7. 命令里不要包含用户的密码、密钥等敏感内容。\n"
        . "8. 别用一堆碎命令空转，能一条查清就不要拆成三条。\n"
        . ($默认主机 > 0
            ? "9. 本项目已绑定默认服务器（编号 {$默认主机}），涉及本项目的操作就用它，不用问用户选哪台。\n"
            : "");
}
