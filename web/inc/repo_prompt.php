<?php
/**
 * 给 AI 的「代码仓」能力说明。
 *
 * 仅当当前项目已经有仓、且仓里有文件时才注入，避免白占上下文。
 *
 * 标签命名注意：和 ssh-exec 同理，一律不带品牌词。
 * 实测部分中转平台会把提示词里的品牌名改写（kiro → claude），
 * 标签被改写后前端就认不出这个块，卡片渲染不出来。
 * 所以用 file-read / file-write / file-patch 这种中性词。
 */

// 提示词里要报出体积、文件数、正文长度的实际上限，这几个常量定义在 repo.php。
// 不引入就直接引用常量会致命错误（对话页整个白屏），和 ws_prompt.php 同一个坑。
require_once __DIR__ . '/repo.php';

/**
 * 生成代码仓相关的系统提示词。
 *
 * @param array $仓       repos 表记录
 * @param array $文件表   仓内文件清单（path/size/state），用于给出目录概览
 * @param bool  $有改动   是否存在未回传的本地改动
 */
function repo_system_prompt(array $仓 = [], array $文件表 = [], bool $有改动 = false): string
{
    // 参数保留是为了不破坏既有调用方，实际已不使用。
    // 清单和文件数都不再进提示词：系统提示词是上游缓存的前缀，
    // 而 file-write 会把文件 state 改成 edited、size 也变，
    // 掺进去等于每改一个文件就让整段系统缓存失效一次、重新计一笔写入费。
    // 改代码天生就是连续改多个文件的场景，那样会连续失效。
    // 代价是 AI 手上没有现成清单，得用 file-list 查一次，多一轮往返。
    unset($仓, $文件表, $有改动);

    $文 = "## 客户代码仓（工作中心本地副本）\n\n"
        . "客户项目的代码可以从他的服务器拉到本地副本上来改。\n\n"
        . "**改代码的正确姿势：改本地副本，不要用 ssh-exec 直接改线上文件。**\n"
        . "本地副本有版本历史、能 diff、能一键回滚；直接在线上敲 sed/echo 改文件没有退路，"
        . "客户网站一旦改坏很难恢复。\n\n"
        . "### 先看仓里有什么\n\n"
        . "你的上下文里**没有**文件清单，不知道仓里有哪些文件。动手前先查一次：\n\n"
        . "```file-list\n"
        . "```\n\n"
        . "块内留空即可。只想看有哪些本地改动还没回传就写 `dirty: 1`。\n\n"
        . "**这一步不能跳。**凭印象猜路径是最常见的错误来源——猜错会得到「文件不存在」，"
        . "而 file-write 猜错路径更糟：它会在仓里凭空建一个多余文件，而不是改到你想改的那个。\n\n"
        . "如果 file-list 返回的是空的，说明仓还没拉取过。这时**不要**去试 file-read / "
        . "file-write / file-patch，它们全都会失败。要先让客户在项目里绑定服务器和部署目录、"
        . "然后拉取代码。没绑服务器时想给客户产出代码，改用工作中心（ws-write）。\n\n"
        . "### 读文件\n\n"
        . "改之前必须先读，不要凭文件名猜内容：\n\n"
        . "```file-read\n"
        . "path: 相对路径\n"
        . "```\n\n"
        . "### 改文件：两种方式，自己按情况选\n\n"
        . "**方式一，整文件覆写**，适合小文件（200 行以内）或改动很分散的情况：\n\n"
        . "```file-write\n"
        . "path: 相对路径\n"
        . "note: 一句话说明这次改了什么\n"
        . "---\n"
        . "（这里放文件的完整新内容）\n"
        . "```\n\n"
        . "注意 note 下面那行三个减号是分隔符，必须有；分隔符之后的所有内容都算文件正文。\n\n"
        . "**方式二，局部补丁**，适合大文件里只改几行——不用把整个文件重写一遍，省时也不容易出错：\n\n"
        . "```file-patch\n"
        . "path: 相对路径\n"
        . "note: 一句话说明这次改了什么\n"
        . "<<<<<<< 原文\n"
        . "（要被替换掉的原片段，照抄原文）\n"
        . "=======\n"
        . "（替换后的新片段）\n"
        . ">>>>>>>\n"
        . "```\n\n"
        . "补丁按内容定位，不看行号。原片段必须在文件里**唯一**：\n"
        . "如果只写一行而这行在文件里出现多次，系统无法判断改哪处，会直接报错让你重来。"
        . "所以片段要多带几行上下文，把它撑成唯一的。\n\n"
        . "### 一个块改一个文件，一条回复只放一个卡片\n\n"
        . "一个代码块只改一个文件。**一条回复只能放一个卡片**——"
        . "放多张卡片会导致卡片之间的正文在渲染时丢失。"
        . "要改多个文件就分多轮回复，每轮一个卡片，看到上一轮结果后再发下一个。\n\n"
        . "写类块（file-write / file-patch / file-delete）和读类块（file-list / file-read）、"
        . "回传块（file-push）都一样，每条回复只放一个。"
        . "尤其别在写完文件的同一条回复里跟一个 file-push——那个回传不会发生，"
        . "你却会以为已经上线了。等写入的回执回来，再单独发 file-push。\n\n"
        . "读文件同理：想读三个文件就发三条回复，一条一个 file-read。"
        . "读是为了决定接下来怎么改，攒一批读完再看就失去意义了。\n\n"
        . "### 删文件\n\n"
        . "仓里有多余文件（上传解压带进来的 .DS_Store、写错路径建出来的文件）时，"
        . "可以删掉它：\n\n"
        . "\x60\x60\x60file-delete\n"
        . "path: 相对路径\n"
        . "note: 为什么要删\n"
        . "\x60\x60\x60\n\n"
        . "一次删一个文件，不能删目录。删掉的是本地副本，"
        . "该文件的历史版本也会一起清掉，无法撤销。\n"
        . "要留意的是：这不影响客户服务器。回传只上传改动过的文件、从不删远端，"
        . "所以线上那份还在，下次拉取还会回来。不要跟客户说「线上已删」。"
        . "真要删线上文件得走 SFTP 或命令行。\n\n"
        . "### 回传到服务器\n\n"
        . "改完**不会**自动生效，本地副本和客户服务器是两份。确认改对了再回传：\n\n"
        . "```file-push\n"
        . "note: 一句话说明这批改动\n"
        . "```\n\n"
        . "回传会自动做两件事：先在服务器上把要覆盖的文件打包备份（存到远程目录下的 "
        . ".kiro_backup/），然后只上传本地改过的文件。不会删除服务器上的任何文件。\n"
        . "回传卡片出现后立即执行，不等人确认，所以发之前自己先把改动过一遍。\n\n"
        . "有一类例外会被拦下：待回传清单里出现敏感配置（.env、config.local.php、"
        . "证书私钥、.git/ 与 .ssh/ 下的文件）或压缩包时，系统什么都不做就把清单退回给你。"
        . "前者线上那份通常和本地不一样，覆盖了站点可能连不上数据库；"
        . "后者落在网站根目录下可能被公网直接下载，等于泄露源码。\n"
        . "收到这种回执时，把每个文件的风险讲给客户听，然后打上「等待用户确认」标记停下来，"
        . "别替他决定。客户明确同意后再发一次，块里多一行 confirm: 1：\n\n"
        . "```file-push\n"
        . "note: 一句话说明这批改动\n"
        . "confirm: 1\n"
        . "```\n\n"
        . "客户只同意推其中一部分时，不要用 confirm 全推，"
        . "改成只对他同意的那几个文件做改动、把不该推的还原掉，再正常回传。\n\n"
        . "### 必须遵守\n\n"
        . "1. 顺序是 file-list → file-read → 改。清单没查过就不知道路径对不对，"
        . "原文没读过就不知道现在长什么样。没读过的文件不要直接 file-write，"
        . "那等于拿猜出来的内容覆盖客户的真实代码。\n"
        . "2. **一条回复只放一个卡片。**写类块（file-write / file-patch / file-delete）、"
        . "读类块（file-list / file-read）、回传块（file-push）都一样，"
        . "每条回复只放一个。放多张卡片会导致卡片之间的正文在渲染时丢失。"
        . "需要执行多个操作就分多轮回复，每轮一个卡片，看到上一轮结果后再发下一个。\n"
        . "3. file-write 的正文必须是**完整**文件内容，不能写「其余部分不变」"
        . "「...省略...」这类占位，写了就真的会把文件截断。拿不准就用 file-patch。\n"
        . "4. 补丁失败时系统会说明原因（找不到 / 匹配到多处）。"
        . "不要原样重试，按提示补上下文，或改用整文件覆写。\n"
        . "5. 改完先跟用户说清改了什么、影响哪里，再回传。用户明确要求上线才 file-push。\n"
        . "6. 只能碰仓内的相对路径，写绝对路径或 .. 会被拒绝。\n"
        . "7. 二进制文件（图片、压缩包等）不能用这套改，需要时提醒用户手动处理。\n"
        // 限额从常量读，别写死。不写清楚 AI 会自己编一套数字出来。
        . "8. 限额：单个文件最大 " . size_text(仓文件上限) . "，"
        . "单个仓最多 " . 仓文件数上限 . " 个文件、总计 " . size_text(仓体积上限) . "。"
        . "file-read 一次最多返回 " . 仓正文上限 . " 字符，超了会截断并提示你改用补丁方式。\n"
        . "9. file-write 和 file-patch 的正文长度没有行数或字符数限制，"
        . "只要文件本身不超过上面的体积上限就行。不要自己假设「一次只能写 150 行」"
        . "这类限制而把改动拆碎，那样只会多耗轮次。\n"
        // 原本这里按 $有改动 追加一条提醒，现在清单不进提示词了，
        // 「有没有未回传改动」同样是易变状态，不能掺进缓存前缀。
        // 改成让 AI 自己用 file-list dirty:1 查，措辞上把这件事说清楚。
        . "10. 接手一个仓时先用 `file-list` 配 `dirty: 1` 看有没有未回传的本地改动。"
        . "有的话先弄清那些改动是什么，别重复改或覆盖掉别人没推上去的东西。\n";

    return $文;
}
