<?php
/**
 * 给 AI 的「直连 SFTP 读改删」能力说明。
 *
 * 仅当项目已绑定服务器且填了部署目录时才注入——两者缺一就没法确定改哪台机器的哪个目录，
 * 注入了也只会让 AI 写出必然失败的块。
 *
 * 标签命名注意：和 ssh-exec / file-read 同理，一律不带品牌词。
 * 实测部分中转平台会改写提示词里的品牌名（kiro → claude），
 * 标签一旦被改写，前端就认不出这个块，卡片渲染不出来。
 * 所以用 sftp-list / sftp-read / sftp-write / sftp-patch / sftp-delete 这种中性词。
 */

// 提示词里要报出体积与条数上限的实际数值，这两个常量定义在 sftp_edit.php。
// 不引入的话直接引用常量会致命错误。
require_once __DIR__ . '/sftp_edit.php';

/**
 * 生成直连 SFTP 相关的系统提示词。
 *
 * @param array $项目 projects 表记录，需含 host_id 与 deploy_dir
 * @param array $主机 ssh_hosts 表记录（name/host/username），用于在提示里点明目标机器
 */
function sftp_system_prompt(array $项目, array $主机 = []): string
{
    $根 = trim((string) ($项目['deploy_dir'] ?? ''));
    if ((int) ($项目['host_id'] ?? 0) <= 0 || $根 === '') {
        return '';
    }
    $根 = rtrim($根, '/');

    $机描述 = $主机
        ? $主机['name'] . '（' . $主机['host'] . '，登录用户 ' . $主机['username'] . '）'
        : '本项目绑定的服务器';

    return "## 改客户网站文件：优先走 SFTP\n\n"
        . "目标服务器：" . $机描述 . "\n"
        . "允许操作的目录：`" . $根 . "`（含其下所有子目录）\n\n"
        . "开发这个网站时，**看文件、改文件、删文件优先用下面的 SFTP 代码块**。\n\n"
        . "原因很实在：SFTP 通道每次写入和删除前，都会自动把原文件备份到远端 "
        . "`.kiro_backup/` 并在数据库里留一份，改坏了能一键还原。"
        . "命令行没有这层保护，一个引号写错就能把客户的文件截断成空。\n"
        . "命令行改文件是允许的，没有任何拦截，只是没有备份兜底，"
        . "所以能用 SFTP 就用 SFTP。\n\n"
        . "### 列目录\n\n"
        . "```sftp-list\n"
        . "dir: 相对部署目录的子路径，留空或写 . 表示部署目录本身\n"
        . "```\n\n"
        . "### 读文件\n\n"
        . "改之前必须先读，不要凭文件名猜内容：\n\n"
        . "```sftp-read\n"
        . "path: 相对部署目录的路径，例如 index.php 或 inc/config.php\n"
        . "```\n\n"
        . "### 改文件：两种方式，按情况选\n\n"
        . "**方式一，局部补丁**（优先用这个）。大文件里只改几行时，不必整篇重写：\n\n"
        . "```sftp-patch\n"
        . "path: 相对路径\n"
        . "note: 一句话说明这次改了什么\n"
        . "<<<<<<< 原文\n"
        . "（要被替换掉的原片段，照抄原文）\n"
        . "=======\n"
        . "（替换后的新片段）\n"
        . ">>>>>>>\n"
        . "```\n\n"
        . "补丁按内容定位，不看行号。原片段必须在文件里**唯一**：只写一行而这行出现多次时，"
        . "系统无法判断改哪处，会报错让你重来。所以片段要多带几行上下文，把它撑成唯一的。\n\n"
        . "**方式二，整文件覆写**，适合小文件（200 行以内）、新建文件，或改动特别分散的情况：\n\n"
        . "```sftp-write\n"
        . "path: 相对路径\n"
        . "note: 一句话说明这次改了什么\n"
        . "---\n"
        . "（这里放文件的完整新内容）\n"
        . "```\n\n"
        . "note 下面那行三个减号是分隔符，必须有；分隔符之后的所有内容都算文件正文。\n\n"
        . "### 删文件\n\n"
        . "```sftp-delete\n"
        . "path: 相对路径\n"
        . "note: 为什么要删\n"
        . "```\n\n"
        . "删除只能删单个文件，不能删目录。删前会自动备份，卡片出现后立即执行，不等人确认，"
        . "所以路径要确认无误再发。\n\n"
        . "### 必须遵守\n\n"
        . "1. 先 sftp-read 看清原文再改。没读过的文件不要直接 sftp-write，"
        . "那等于拿猜出来的内容覆盖客户的真实代码。\n"
        . "2. **一条回复只放一个卡片。**无论是写类块（sftp-write / sftp-patch / sftp-delete）"
        . "还是读类块（sftp-list / sftp-read），每条回复只放一个——"
        . "放多张卡片会导致卡片之间的正文在渲染时丢失。"
        . "需要执行多个操作就分多轮回复，每轮一个卡片，看到上一轮结果后再发下一个。\n"
        . "3. sftp-write 的正文必须是**完整**文件内容，不能写「其余部分不变」"
        . "「...省略...」这类占位，写了就真的会把文件截断。拿不准就用 sftp-patch。\n"
        . "4. 这些改动**直接落在客户的线上服务器上，立即生效**，没有本地副本做缓冲。"
        . "所以改动前先想清楚影响，动静大的改动先跟用户说明再动手。\n"
        . "5. 路径只能落在 `" . $根 . "` 之内。写绝对路径要以它开头，"
        . "带 .. 往上跳会被直接拒绝。\n"
        . "6. 二进制文件（图片、压缩包等）不能用这套读改，需要时提醒用户手动处理。\n"
        . "7. 补丁失败时系统会说明原因（找不到 / 匹配到多处）。不要原样重试，"
        . "按提示补上下文，或改用整文件覆写。\n"
        // 限额从常量读，别写死。不写清楚 AI 会自己编一套数字出来。
        . "8. 限额：单个文件最大 " . size_text(直改体积上限) . "，"
        . "列目录一次最多返回 " . 直改列表上限 . " 条。"
        . "sftp-write 和 sftp-patch 的正文长度没有行数或字符数限制，"
        . "只要文件不超过体积上限就行——不要自己假设「一次只能写 150 行」这类限制而把改动拆碎。\n"
        . "9. SFTP 失败时先判断原因：补丁匹配不上就补上下文重发，"
        . "权限或路径问题请用户处理。确实需要时也可以改用命令行，"
        . "但要清楚那样就没有备份可还原了。\n"
        . "10. 不必用命令行去「验证」SFTP 的结果（比如 cat 一下看写没写进去）。"
        . "SFTP 写入后系统已自动复核远端体积并把结果告诉你，够用了。\n";
}
